//! Validated, backend-neutral contract for a one-file Telegram upload.
//!
//! The UI stages bytes under its own private session directory and passes only
//! an opaque UUID. No external content URI or filesystem path crosses JNI.

use serde::{Deserialize, Serialize};

use crate::error::{CoreError, Result};

pub const MAX_OUTGOING_MEDIA_BYTES: u64 = 2 * 1024 * 1024 * 1024;
pub const MAX_OUTGOING_CAPTION_CHARS: usize = 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum OutgoingMediaKind {
    Photo,
    Video,
    Document,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SendMediaRequest {
    pub chat_id: i64,
    /// UUID generated by Android for the private staged file (not a path).
    pub upload_id: String,
    pub kind: OutgoingMediaKind,
    /// Telegram-visible sanitized basename; never used as a filesystem path.
    pub filename: String,
    pub mime_type: String,
    pub size_bytes: u64,
    #[serde(default)]
    pub caption: String,
}

impl SendMediaRequest {
    pub fn validate(&self) -> Result<()> {
        if self.chat_id == 0 {
            return Err(CoreError::InvalidInput("media destination must be non-zero".into()));
        }
        validate_upload_id(&self.upload_id)?;
        if self.size_bytes == 0 || self.size_bytes > MAX_OUTGOING_MEDIA_BYTES {
            return Err(CoreError::InvalidInput("media size must be between 1 byte and 2 GiB".into()));
        }
        if self.filename.is_empty()
            || self.filename.len() > 128
            || self.filename == "."
            || self.filename == ".."
            || self.filename.chars().any(|c| c.is_control() || c == '/' || c == '\\')
        {
            return Err(CoreError::InvalidInput("invalid media filename".into()));
        }
        let mut parts = self.mime_type.split('/');
        let primary = parts.next().unwrap_or("");
        let subtype = parts.next().unwrap_or("");
        if primary.is_empty()
            || subtype.is_empty()
            || parts.next().is_some()
            || self.mime_type.len() > 127
            || !self.mime_type.bytes().all(|b| b.is_ascii_alphanumeric() || matches!(b, b'/' | b'-' | b'+' | b'.' | b'_'))
        {
            return Err(CoreError::InvalidInput("invalid media MIME type".into()));
        }
        if self.caption.chars().count() > MAX_OUTGOING_CAPTION_CHARS {
            return Err(CoreError::InvalidInput("media caption exceeds 1024 characters".into()));
        }
        if matches!(self.kind, OutgoingMediaKind::Photo) && primary != "image" {
            return Err(CoreError::InvalidInput("photo MIME type must be image/*".into()));
        }
        if matches!(self.kind, OutgoingMediaKind::Video) && primary != "video" {
            return Err(CoreError::InvalidInput("video MIME type must be video/*".into()));
        }
        Ok(())
    }
}

pub fn validate_upload_id(id: &str) -> Result<()> {
    let bytes = id.as_bytes();
    if bytes.len() != 36 || bytes.iter().enumerate().any(|(index, byte)| {
        if matches!(index, 8 | 13 | 18 | 23) {
            *byte != b'-'
        } else {
            !byte.is_ascii_hexdigit()
        }
    }) {
        return Err(CoreError::InvalidInput("upload id must be a UUID, not a file path".into()));
    }
    Ok(())
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MediaUploadStatus {
    Queued,
    Uploading,
    Sent,
    Failed,
    Cancelled,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MediaUploadUpdate {
    pub upload_id: String,
    pub chat_id: i64,
    pub generation: u64,
    pub status: MediaUploadStatus,
    pub bytes_sent: u64,
    pub total_bytes: u64,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub server_message_id: Option<i64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> SendMediaRequest {
        SendMediaRequest {
            chat_id: -100,
            upload_id: "123e4567-e89b-12d3-a456-426614174000".into(),
            kind: OutgoingMediaKind::Video,
            filename: "clip.mp4".into(),
            mime_type: "video/mp4".into(),
            size_bytes: 4096,
            caption: "Caption".into(),
        }
    }

    #[test]
    fn validated_media_command_round_trips() {
        let request = sample();
        request.validate().unwrap();
        assert_eq!(serde_json::from_str::<SendMediaRequest>(&serde_json::to_string(&request).unwrap()).unwrap(), request);
    }

    #[test]
    fn rejects_paths_oversize_mismatched_media_and_invalid_uuid() {
        let mut bad = sample();
        bad.upload_id = "../escape".into();
        assert!(bad.validate().is_err());
        let mut bad = sample();
        bad.filename = "../../secret.txt".into();
        assert!(bad.validate().is_err());
        let mut bad = sample();
        bad.mime_type = "image/png".into();
        assert!(bad.validate().is_err());
        let mut bad = sample();
        bad.size_bytes = MAX_OUTGOING_MEDIA_BYTES + 1;
        assert!(bad.validate().is_err());
        let mut bad = sample();
        bad.caption = "x".repeat(MAX_OUTGOING_CAPTION_CHARS + 1);
        assert!(bad.validate().is_err());
        let mut bad = sample();
        bad.filename = "foo\\bar.jpg".into();
        assert!(bad.validate().is_err());
    }

    #[test]
    fn upload_events_encode_status_and_server_id() {
        let update = MediaUploadUpdate {
            upload_id: sample().upload_id,
            chat_id: -100,
            generation: 3,
            status: MediaUploadStatus::Sent,
            bytes_sent: 4096,
            total_bytes: 4096,
            server_message_id: Some(42),
            error: None,
        };
        assert_eq!(serde_json::from_str::<MediaUploadUpdate>(&serde_json::to_string(&update).unwrap()).unwrap(), update);
    }
}
